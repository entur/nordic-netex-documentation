#!/usr/bin/env python3
"""
Generate Table_<Class>.md and the structure tree in Description_<Class>.md
from the validated examples and the ontology.

Rows come from the examples (Example_*.xml in the object folder): every element
and attribute below the object, in example order. Child objects that have
their own Table become a single linked row. XML types come from profile:onClass
(or doc:forClass for unprofiled documentation), not folder-name guesses.
Generation refuses empty tables and prepares all selected classes before writing.

Cardinality and description are looked up per row in this order:

  1. Nordic Profile   profile:ProfileMember (profile:cardinality, skos:definition)
  2. Entur            Entur ProfileMember, then Entur sub-profile SHACL shapes,
                      labelled with the sub-profile's skos:prefLabel
  3. NeTEx XSD        class-scoped SHACL shapes in base (via rdfs:subClassOf)

If an Entur sub-profile constrains a field differently from the value shown,
the cardinality becomes the conditional `*..*`. Rows without a description
are shown as `?` and listed in the report. Ambiguous shared annotations and
unrepresented substitutions/combined choice constraints are not guessed.

Hand-written content lives in Overrides_<Class>.json next to the examples. A
manual description is used when no profile definition exists (it wins over the
generic NeTEx base text); a manual type or link only fills a gap. The Source
column shows where each description comes from.

Element order follows the XSD sequence, read from netex:xsdSequenceOrder in the
base ontology (inherited properties first). Attributes come first. Elements
without a sequence position (for example substitution members) are placed after
their nearest preceding sibling in the examples and listed in the report.

Usage:
    python scripts/generate_tables.py                       # prototype classes
    python scripts/generate_tables.py ServiceJourney Line   # selected classes
    python scripts/generate_tables.py --check               # fail if files are stale
    python scripts/generate_tables.py --coverage            # profile fields missing from the examples

Requires: Python 3.10+, rdflib
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from dataclasses import dataclass, field
from pathlib import Path

from rdflib import BNode, Graph, Namespace, RDFS, URIRef
from rdflib.namespace import OWL, SH, SKOS

REPO_ROOT = Path(__file__).resolve().parent.parent
DOC_TTL = REPO_ROOT / "ontology" / "netex-nordic-documentation.ttl"
ENTUR_DIR = REPO_ROOT / "ontology" / "entur-netex-ontology"
NORDIC_DIR = ENTUR_DIR / "nordic-netex-ontology"

NETEX = Namespace("https://netex-cen.eu/ontology#")
PROFILE = Namespace("https://netex-cen.eu/profile#")
NORDIC_NS = "https://netex-cen.eu/nordic#"
ENTUR_NS = "https://entur.org/ontology#"
DOC = Namespace("https://netex-cen.eu/doc#")
GML_NS = "http://www.opengis.net/gml/3.2"
NETEX_XML_NS = "http://www.netex.org.uk/netex"
XSD_NS = "http://www.w3.org/2001/XMLSchema#"

PROTOTYPE = ["ServiceJourney", "StopPlace"]
CONDITIONAL = "[`*..*`](../../guides/NeTExConventions/NeTEx_Conventions.md)"
GENERATED_NOTE = "<!-- Generated by scripts/generate_tables.py from the examples and the ontology. Do not edit by hand. -->"
TREE_START = "<!-- generated:structure:start -->"
TREE_END = "<!-- generated:structure:end -->"
SKIP_NESTED_ATTRS = {"version", "lang"}
OVERRIDE_KEYS = {"description", "type", "link"}
SOURCE_LEGEND = (
    "**Source** shows where the description comes from: **Nordic** – the Nordic Profile; "
    "**Entur** – Entur's profile or a service layer; **Manual** – hand-written in `{file}`; "
    "**NeTEx** – inherited from the NeTEx base, generic and not profile-specific. "
    "A type marked *(manual)* is hand-written because the ontology has no type for it."
)


def local(uri) -> str:
    s = str(uri)
    return s.rsplit("#", 1)[-1].rsplit("}", 1)[-1]


def lc(name: str) -> str:
    return name[:1].lower() + name[1:]


# ---------------------------------------------------------------- ontology

@dataclass
class FieldRule:
    card: str | None = None
    definition: str | None = None


@dataclass
class BaseInfo:
    min: int = 0
    max: int | None = None
    range: URIRef | None = None
    type: str | None = None
    comment: str | None = None


@dataclass
class Ontology:
    np: dict = field(default_factory=dict)        # (Class, path) -> FieldRule
    entur: dict = field(default_factory=dict)     # (Class, path) -> FieldRule
    services: dict = field(default_factory=dict)  # (Class, prop) -> [(label, min, max, desc)]
    base_shapes: dict = field(default_factory=dict)  # targetClass -> {prop: BaseInfo}
    base: Graph | None = None
    sequence: dict = field(default_factory=dict)  # class -> {prop: (depth, order)}, filled lazily


def load_ontology() -> Ontology:
    ont = Ontology()

    profile = Graph()
    profile.parse(NORDIC_DIR / "netex-nordic.ttl")
    profile.parse(ENTUR_DIR / "netex-entur.ttl")
    for member in profile.subjects(None, PROFILE.ProfileMember):
        node = profile.value(member, PROFILE.memberOf)
        cls = profile.value(node, PROFILE.onClass)
        path = str(profile.value(member, PROFILE.path) or "")
        name = local(cls)
        if path.startswith(name + "/"):
            path = path[len(name) + 1:]
        rule = FieldRule(
            card=str(profile.value(member, PROFILE.cardinality) or "") or None,
            definition=str(profile.value(member, SKOS.definition) or "") or None,
        )
        target = ont.np if str(node).startswith(NORDIC_NS) else ont.entur
        target[(name, path)] = rule

    for f in sorted(ENTUR_DIR.glob("netex-entur-*.ttl")):
        g = Graph()
        g.parse(f)
        label = next((str(o) for o in g.objects(None, SKOS.prefLabel)), f.stem)
        for shape, cls in g.subject_objects(SH.targetClass):
            for prop in g.objects(shape, SH.property):
                path = g.value(prop, SH.path)
                if not isinstance(path, URIRef):
                    continue
                mn, mx = g.value(prop, SH.minCount), g.value(prop, SH.maxCount)
                desc = g.value(prop, SH.description)
                ont.services.setdefault((local(cls), local(path)), []).append(
                    (label, int(mn) if mn is not None else None,
                     int(mx) if mx is not None else None, str(desc) if desc else None))

    base = Graph()
    for f in sorted((NORDIC_DIR / "base").glob("*.ttl")):
        base.parse(f)
    ont.base_shapes = scoped_base_shapes(base)
    ont.base = base
    return ont


def unique(values):
    values = set(values)
    return next(iter(values)) if len(values) == 1 else None


def scoped_base_shapes(base: Graph) -> dict:
    """Read per-class constraints; shared property annotations may be ambiguous."""
    owners = {}
    for shape, cls in base.subject_objects(SH.targetClass):
        for prop in base.objects(shape, SH.property):
            path = base.value(prop, SH.path)
            if isinstance(path, URIRef):
                owners.setdefault(path, set()).add(cls)
    shapes = {}
    for shape, cls in base.subject_objects(SH.targetClass):
        props = shapes.setdefault(cls, {})
        for prop in base.objects(shape, SH.property):
            path = base.value(prop, SH.path)
            if not isinstance(path, URIRef):
                continue
            mn, mx = base.value(prop, SH.minCount), base.value(prop, SH.maxCount)
            rng, datatype = base.value(prop, SH["class"]), base.value(prop, SH.datatype)
            global_type = unique(base.objects(path, NETEX.xsdType))
            is_ref = bool(base.value(path, NETEX.isReference)) or local(path).endswith("Ref")
            if rng and not is_ref:
                typ = local(rng)
            elif is_ref:
                # A reference structure's XML type differs from its target class.
                typ = str(global_type) if global_type is not None else None
            elif datatype:
                typ = str(global_type) if global_type is not None else (
                    "xsd:" + local(datatype) if str(datatype).startswith(XSD_NS) else local(datatype))
            else:
                # Enum/list constraints may have sh:in without an explicit range.
                typ = str(global_type) if global_type is not None else None
            comment = unique(base.objects(prop, SH.description))
            if comment is None and len(owners.get(path, ())) == 1:
                comment = unique(base.objects(path, RDFS.comment))
            props[local(path)] = BaseInfo(
                min=int(mn) if mn is not None else 0,
                max=int(mx) if mx is not None else None,
                range=rng,
                type=typ,
                comment=str(comment) if comment is not None else None,
            )
    return shapes


def ancestors(g: Graph, cls: URIRef) -> list[URIRef]:
    seen, todo = [], [cls]
    while todo:
        c = todo.pop(0)
        if c in seen:
            continue
        seen.append(c)
        todo.extend(o for o in g.objects(c, RDFS.subClassOf) if isinstance(o, URIRef))
    return seen


def sequence_rank(ont: Ontology, cls: URIRef) -> dict:
    """XSD sequence position per property: inherited (more general) classes first."""
    if cls not in ont.sequence:
        rank = {}
        for depth, c in enumerate(reversed(ancestors(ont.base, cls))):
            for r in ont.base.objects(c, RDFS.subClassOf):
                if not isinstance(r, BNode):
                    continue
                n, prop = ont.base.value(r, NETEX.xsdSequenceOrder), ont.base.value(r, OWL.onProperty)
                if n is not None and prop is not None:
                    rank.setdefault(local(prop), (depth, int(n)))
        ont.sequence[cls] = rank
    return ont.sequence[cls]


def base_lookup(ont: Ontology, root: str, segments: list[str]) -> BaseInfo | None:
    cur, info = NETEX[root], None
    for seg in segments:
        if cur is None:
            return None
        name = seg.split(":", 1)[-1]
        prop = name[1:] if name.startswith("@") else lc(name)
        info = next((ont.base_shapes[a][prop] for a in ancestors(ont.base, cur)
                     if prop in ont.base_shapes.get(a, {})), None)
        if info is None:
            return None
        cur = info.range
    return info


# ---------------------------------------------------------------- documentation index

@dataclass(frozen=True)
class Documentation:
    scope: str
    folder: Path
    target: str


def documented_classes() -> dict[str, Documentation]:
    """Resolve document folders to XML classes using the explicit profile mapping."""
    index, profiles = Graph(), Graph()
    index.parse(DOC_TTL, format="turtle")
    for p in [*sorted(NORDIC_DIR.glob("*.ttl")), *sorted(ENTUR_DIR.glob("netex-entur*.ttl"))]:
        profiles.parse(p, format="turtle")
    out = {}
    for node, table in index.subject_objects(DOC.table):
        targets = set(profiles.objects(node, PROFILE.onClass)) | set(index.objects(node, DOC.forClass))
        if len(targets) != 1:
            raise ValueError(f"{node}: expected one explicit profile:onClass or doc:forClass mapping")
        target = next(iter(targets))
        if not str(target).startswith(str(NETEX)):
            raise ValueError(f"{node}: expected a NeTEx class, got {target}")
        folder = (REPO_ROOT / str(table)).resolve().parent
        if not folder.is_relative_to(REPO_ROOT.resolve()):
            raise ValueError(f"Documentation path escapes repository: {table}")
        scope = "entur" if str(node).startswith(ENTUR_NS) else "nordic"
        key = folder.name
        entry = Documentation(scope, folder, local(target))
        if key in out and out[key] != entry:
            raise ValueError(f"Conflicting documentation mapping for {key}")
        out[key] = entry
    return out


# ---------------------------------------------------------------- rows from examples

@dataclass
class Node:
    name: str
    kind: str  # element | attribute | ref | object
    link: str | None = None


class Rows:
    def __init__(self):
        self.example_files: list[Path] = []
        self.object_count = 0
        self.nodes: dict[str, Node] = {}
        self.children: dict[str, list[str]] = {"": []}
        self.observed: dict[str, list[tuple[str, list[str]]]] = {}  # parent -> [(example, child order)]

    def add(self, parent: str, path: str, node: Node, siblings: list[str]):
        if path not in self.nodes:
            self.nodes[path] = node
            order = self.children.setdefault(parent, [])
            later = siblings[siblings.index(path) + 1:]
            nxt = next((k for k in later if k in order), None)
            order.insert(order.index(nxt) if nxt else len(order), path)
        self.children.setdefault(path, [])

    def walk(self):
        def rec(parent):
            for p in self.children.get(parent, []):
                yield p
                yield from rec(p)
        yield from rec("")


def tag(el) -> str:
    name = el.tag.rsplit("}", 1)[-1]
    return "gml:" + name if el.tag.startswith("{" + GML_NS + "}") else name


def collect(cls: str, docs: dict) -> Rows:
    rows = Rows()
    doc = docs[cls]
    examples = sorted(doc.folder.glob("Example_*.xml"))
    rows.example_files = examples
    by_target = {}
    for key, entry in docs.items():
        if entry.target in by_target and by_target[entry.target] != key:
            raise ValueError(f"Ambiguous documentation folders for {entry.target}")
        by_target[entry.target] = key

    def visit(el, prefix: str, is_root: bool):
        attrs, elems = [], []
        for attr in el.attrib:
            a = attr.rsplit("}", 1)[-1]
            if is_root or a not in SKIP_NESTED_ATTRS:
                attrs.append((f"{prefix}@{a}", Node(f"@{a}", "attribute"), None))
        for child in el:
            name = tag(child)
            path = f"{prefix}{name}"
            if name.endswith("Ref") and "ref" in child.attrib:
                target = name[:-3]
                elems.append((f"{path}/@ref", Node(f"{name}/@ref", "ref", by_target.get(target)), None))
            elif name in by_target and name != doc.target:
                elems.append((path, Node(name, "object", by_target[name]), None))
            else:
                elems.append((path, Node(name, "element"), child))
        keyed = attrs + elems
        order = [k for k, *_ in keyed]
        rows.observed.setdefault(prefix.rstrip("/"), []).append(
            (current.name, list(dict.fromkeys(k for k, *_ in elems))))
        for path, node, _ in keyed:
            rows.add(prefix.rstrip("/"), path, node, order)
        for path, _, child in elems:
            if child is not None and (len(child) or any(
                    a.rsplit("}", 1)[-1] not in SKIP_NESTED_ATTRS for a in child.attrib)):
                visit(child, path + "/", False)

    current = None
    for ex in examples:
        current = ex
        for el in ET.parse(ex).iter():
            if el.tag == "{" + NETEX_XML_NS + "}" + doc.target:
                rows.object_count += 1
                visit(el, "", True)
    return rows


def element_prop(node: Node) -> str:
    name = node.name[:-len("/@ref")] if node.kind == "ref" else node.name
    return lc(name.split(":", 1)[-1])


def order_rows(rows: Rows, root: str, ont: Ontology, report: list, label: str | None = None):
    """Sort each element's children by the XSD sequence; attributes first."""
    label = label or root
    for parent, kids in rows.children.items():
        if not kids:
            continue
        if parent == "":
            cls = NETEX[root]
        else:
            info = base_lookup(ont, root, parent.split("/"))
            cls = info.range if info else None
        rank = sequence_rank(ont, cls) if cls is not None else {}
        attrs = [k for k in kids if rows.nodes[k].kind == "attribute"]
        elems = [k for k in kids if rows.nodes[k].kind != "attribute"]
        if not rank:
            if len(elems) > 1:
                report.append(f"{label}: {parent or root} (no XSD sequence for its children; example order kept)")
            rows.children[parent] = attrs + elems
            continue
        known = sorted((k for k in elems if element_prop(rows.nodes[k]) in rank),
                       key=lambda k: rank[element_prop(rows.nodes[k])])
        ordered = list(known)
        for i, k in enumerate(elems):
            if k in known:
                continue
            # No sequence position: keep it right after its nearest preceding sibling in the examples.
            anchor = next((p for p in reversed(elems[:i]) if p in ordered), None)
            ordered.insert(ordered.index(anchor) + 1 if anchor else 0, k)
            where = f"after {rows.nodes[anchor].name}" if anchor else "first"
            report.append(f"{label}: {k} (no XSD sequence position; placed {where} as in the examples)")
        rows.children[parent] = attrs + ordered
    check_order_against_examples(rows, label)


def check_order_against_examples(rows: Rows, label: str):
    """The examples are XSD-valid, so the generated order must never contradict one of them."""
    for parent, seen in rows.observed.items():
        final = rows.children.get(parent, [])
        for example, order in seen:
            shown = [k for k in final if k in order]
            if shown != order:
                raise ValueError(
                    f"{label}: generated order under '{parent or label}' contradicts {example}: "
                    f"{' > '.join(shown)} vs {' > '.join(order)}")


# ---------------------------------------------------------------- hand-written overrides

def overrides_file(folder: Path, cls: str) -> Path:
    return folder / f"Overrides_{cls}.json"


def load_overrides(folder: Path, cls: str) -> dict:
    """Hand-written descriptions, types and links, keyed by row path."""
    path = overrides_file(folder, cls)
    if not path.exists():
        return {"fields": {}, "structure_note": None}
    data = json.loads(path.read_text(encoding="utf-8"))
    fields = data.get("fields", {})
    for key, value in fields.items():
        unknown = set(value) - OVERRIDE_KEYS
        if unknown:
            raise ValueError(f"{path.name}: {key}: unknown keys {sorted(unknown)}")
    return {"fields": fields, "structure_note": data.get("structure_note")}


# ---------------------------------------------------------------- resolution

def fmt(mn, mx) -> str:
    return f"{mn}..{'n' if mx is None else mx}"


def resolve(cls: str, scope: str, path: str, ont: Ontology, manual: dict | None = None):
    """Return (cardinality, type, description, description source, type is manual)."""
    manual = manual or {}
    np_rule, en_rule = ont.np.get((cls, path)), ont.entur.get((cls, path))
    segments = path[:-len("/@ref")].split("/") if path.endswith("/@ref") else path.split("/")
    base = base_lookup(ont, cls, segments)
    services = ont.services.get((cls, lc(segments[0]).lstrip("@")), []) if len(segments) == 1 else []
    entur_tag = "" if scope == "entur" else "**Entur:** "

    def service_card(mn, mx):
        return fmt(base.min if mn is None else mn, base.max if mx is None else mx)

    if np_rule and np_rule.card:
        card = np_rule.card
    elif en_rule and en_rule.card:
        card = entur_tag + en_rule.card
    elif len(services) == 1 and base:
        label, mn, mx, _ = services[0]
        card = f"**Entur – {label}:** " + service_card(mn, mx)
    elif base:
        card = fmt(base.min, base.max)
    else:
        card = "?"

    # An Entur sub-profile that disagrees with the shown value makes the field conditional.
    if services and base and {service_card(mn, mx) for _, mn, mx, _ in services} - {card.rsplit(" ", 1)[-1]}:
        card = CONDITIONAL

    if np_rule and np_rule.definition:
        desc, source = np_rule.definition, "Nordic"
    elif en_rule and en_rule.definition:
        desc, source = en_rule.definition, "Entur"
    elif any(d for *_, d in services):
        label, *_, d = next(s for s in services if s[3])
        desc, source = d, f"Entur – {label}"
    elif manual.get("description"):
        desc, source = manual["description"], "Manual"
    elif base and base.comment:
        desc, source = base.comment, "NeTEx"
    else:
        desc, source = "?", "–"

    if base and base.type:
        typ, typ_manual = base.type, False
    elif manual.get("type"):
        typ, typ_manual = manual["type"], True
    else:
        typ, typ_manual = "?", False
    return card, typ, desc.replace("|", "\\|"), source, typ_manual


# ---------------------------------------------------------------- rendering

def element_cell(node: Node, manual_link: str | None = None) -> str:
    target = f"../{node.link}/Table_{node.link}.md" if node.link else manual_link
    if target and node.kind == "ref":
        return f"[{node.name[:-5]}]({target})/@ref"
    if target:
        return f"[{node.name}]({target})"
    return node.name


def tree_lines(rows: Rows, cards: dict, root: str, emoji: bool) -> list[str]:
    lines = [] if emoji else [root]

    def label(p: str) -> str:
        card = re.sub(r"\*\*[^*]+:\*\* ", "", cards[p].replace(CONDITIONAL, "*..*"))
        return f"{rows.nodes[p].name} ({card})"

    def rec(parent: str, prefix: str, depth: int):
        kids = rows.children.get(parent, [])
        for i, p in enumerate(kids):
            last = i == len(kids) - 1
            if emoji:
                node = rows.nodes[p]
                icon = "🔗" if node.kind == "ref" else ("📁" if rows.children.get(p) else "📄")
                branch = "" if depth == 0 else ("└── " if last else "├── ")
                lines.append(f"{prefix}{branch}{icon} {label(p)}")
                child_prefix = "   " if depth == 0 else prefix + ("    " if last else "│   ")
            else:
                lines.append(f"{prefix} {'└─' if last else '├─'} {label(p)}")
                child_prefix = prefix + ("    " if last else " │  ")
            rec(p, child_prefix, depth + 1)

    rec("", "", 0)
    return lines


def render(cls: str, scope: str, rows: Rows, ont: Ontology, report: list, target: str | None = None,
           overrides: dict | None = None):
    target = target or cls
    overrides = overrides or {"fields": {}, "structure_note": None}
    manual_fields = overrides["fields"]
    order_rows(rows, target, ont, report, cls)
    cards, table = {}, []
    for path in rows.walk():
        node = rows.nodes[path]
        manual = manual_fields.get(path, {})
        card, typ, desc, source, typ_manual = resolve(target, scope, path, ont, manual)
        cards[path] = card
        missing = [name for name, value in (("cardinality", card), ("type", typ), ("description", desc)) if value == "?"]
        if missing:
            report.append(f"{cls}: {path} (missing {', '.join(missing)})")
        if manual.get("description") and source != "Manual":
            report.append(f"{cls}: {path} (manual description not used; {source} definition takes precedence)")
        typ_cell = f"{typ} *(manual)*" if typ_manual else typ
        table.append(f"| {element_cell(node, manual.get('link'))} | {typ_cell} | {card} | {desc} | {source} | {path} |")
    for path in sorted(set(manual_fields) - set(rows.nodes)):
        report.append(f"{cls}: {path} (override has no matching row in the examples)")

    tree = "\n".join(tree_lines(rows, cards, target, emoji=False))
    md = "\n".join([
        f"# Table — {cls}",
        "",
        GENERATED_NOTE,
        "",
        "## Structure Overview",
        "",
        "```text",
        tree,
        "```",
        "",
        "## Table",
        "",
        "| Element | Type | Cardinality | Description | Source | Path |",
        "|---------|------|-------------|-------------|--------|------|",
        *table,
        "",
        SOURCE_LEGEND.format(file=f"Overrides_{cls}.json"),
        "",
    ])
    note = overrides.get("structure_note")
    note_lines = ["", "> [!NOTE]", f"> **Manual:** {note}"] if note else []
    desc_tree = "\n".join([TREE_START, "```text", *tree_lines(rows, cards, target, emoji=True), "```",
                           *note_lines, TREE_END])
    return md, desc_tree


def with_description_tree(text: str, block: str) -> str:
    if TREE_START in text or TREE_END in text:
        if text.count(TREE_START) != 1 or text.count(TREE_END) != 1:
            raise ValueError("Description must have one balanced pair of generated structure markers")
        pattern = re.escape(TREE_START) + r".*?" + re.escape(TREE_END)
        updated, count = re.subn(pattern, lambda _: block, text, flags=re.S)
    else:
        pattern = r"(## 2\. Structure Overview[^\S\n]*\n\s*)```[^\n]*\n.*?\n```"
        updated, count = re.subn(pattern, lambda m: m.group(1) + block, text, count=1, flags=re.S)
    if count != 1:
        raise ValueError("Cannot locate the Description structure tree; refusing partial generation")
    return updated


# ---------------------------------------------------------------- main

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("classes", nargs="*", default=None)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    parser.add_argument("--coverage", action="store_true",
                        help="only report profile fields missing from the examples (all classes if none given)")
    args = parser.parse_args()

    try:
        docs = documented_classes()
        classes = sorted(docs) if args.coverage and not args.classes else args.classes or PROTOTYPE
        selections = []
        for cls in classes:
            if cls not in docs:
                raise ValueError(f"{cls}: no documented class with an explicit mapping")
            doc = docs[cls]
            rows = collect(cls, docs)
            if not args.coverage and not rows.nodes:
                reason = "no Example_*.xml files" if not rows.example_files else f"no {doc.target} instances in the examples"
                raise ValueError(f"{cls}: {reason}; refusing to overwrite documentation with an empty table")
            if args.coverage and not rows.nodes:
                print(f"{cls}: no matching examples (coverage audit only; generation would fail)")
            selections.append((cls, doc, rows, load_overrides(doc.folder, cls)))
        ont = load_ontology()
        report, stale, uncovered, outputs = [], [], {}, {}
        for cls, doc, rows, overrides in selections:
            members = sorted({p for c, p in [*ont.np, *ont.entur] if c == doc.target})
            uncovered[cls] = ([p for p in members if p not in rows.nodes], len(members))
            if args.coverage:
                continue
            md, desc_tree = render(cls, doc.scope, rows, ont, report, doc.target, overrides)
            outputs[doc.folder / f"Table_{cls}.md"] = md
            desc_file = doc.folder / f"Description_{cls}.md"
            if desc_file.exists():
                outputs[desc_file] = with_description_tree(desc_file.read_text(encoding="utf-8"), desc_tree)
    except (ValueError, ET.ParseError, OSError, json.JSONDecodeError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2

    # Prepare every selected class before writing anything: invalid input cannot
    # erase a table or leave earlier classes partially regenerated.
    for path, content in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == content:
            continue
        if args.check:
            stale.append(path.relative_to(REPO_ROOT))
        else:
            path.write_text(content, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(REPO_ROOT)}")

    if report:
        print(f"\nFields needing attention ({len(report)}):")
        for line in report:
            print(f"  {line}")
    missing = {c: v for c, v in uncovered.items() if v[0]}
    if missing:
        total = sum(len(v[0]) for v in missing.values())
        print(f"\nProfile fields not shown in any example ({total}):")
        for cls, (paths, count) in sorted(missing.items()):
            print(f"  {cls} ({len(paths)} of {count}): {', '.join(paths)}")
    if stale:
        print("\nStale generated files (run scripts/generate_tables.py):")
        for p in stale:
            print(f"  {p}")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
